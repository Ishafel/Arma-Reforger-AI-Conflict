param([string]$RepositoryRoot=(Split-Path -Parent $PSScriptRoot),[switch]$Check)
$ErrorActionPreference='Stop'
. (Join-Path $PSScriptRoot 'AICF_Scenarios.ps1')
$catalog=Get-AICFScenarioCatalog -Path (Join-Path $RepositoryRoot 'tools/config/AICF_Scenarios.json')
$lines=[Collections.Generic.List[string]]::new()
$lines.Add('// Generated by tools/Update-AICFScenarioRegistry.ps1 from AICF_Scenarios.json.')
$lines.Add('// Конкретные карты/ресурсы/графы принадлежат integration addon.')
$lines.Add('modded class AICF_ScenarioRegistry')
$lines.Add('{')
$lines.Add("`toverride void Build(array<ref AICF_ScenarioVariant> variants)")
$lines.Add("`t{")
$lines.Add("`t`tsuper.Build(variants);")
$lines.Add("`t`tAICF_ScenarioVariant variant;")
$pairs=@{}
foreach($entry in $catalog.variants){
    if($entry.mapIndex -notin @(0,1,2) -or $entry.contentIndex -notin @(0,1,2)){throw 'Invalid menu indices'}
    $pair="$($entry.mapIndex):$($entry.contentIndex)"
    if($pairs.ContainsKey($pair)){throw 'Duplicate menu combination'}
    $pairs[$pair]=$true
    $graph=$catalog.graphs.PSObject.Properties[$entry.graph].Value
    $owner=@($catalog.localProjects.PSObject.Properties|Where-Object {$_.Value -eq $entry.graph}).Name
    if(@($owner).Count -ne 1 -or $owner -notin $graph.addons){throw 'Missing scenario owner'}
    $mapKey=@('Arland','Everon','EveronNorth')[$entry.mapIndex]
    $west=@('US','USMC','NATO')[$entry.contentIndex]
    $east=@('USSR','MSV','Russia')[$entry.contentIndex]
    $lines.Add("`t`tvariant = new AICF_ScenarioVariant();")
    $lines.Add("`t`tvariant.m_sKey = `"$($entry.name)`";")
    $lines.Add("`t`tvariant.m_iMap = $($entry.mapIndex);")
    $lines.Add("`t`tvariant.m_iContent = $($entry.contentIndex);")
    $lines.Add("`t`tvariant.m_sMapLabel = `"{AICF:AICF_Setup_Map_$mapKey}`";")
    $preview=$catalog.previewHeaders.PSObject.Properties[[string]$entry.mapIndex].Value
    if($preview -notmatch '^\{[A-F0-9]{16}\}Missions/[^\r\n"]+\.conf$'){throw 'Invalid preview header'}
    $lines.Add("`t`tvariant.m_sPreviewHeader = `"$preview`";")
    $lines.Add("`t`tvariant.m_sWestLabel = `"{AICF:AICF_Setup_$west}`";")
    $lines.Add("`t`tvariant.m_sEastLabel = `"{AICF:AICF_Setup_$east}`";")
    $lines.Add("`t`tvariant.m_sOwner = `"$owner`";")
    foreach($id in $graph.addons){$lines.Add("`t`tvariant.m_aAddons.Insert(`"$id`");")}
    foreach($id in $graph.addons){
        if($id -notin $catalog.localProjects.PSObject.Properties.Name){
            $lines.Add("`t`tvariant.m_aContentAddons.Insert(`"$id`");")
        }
    }
    foreach($mode in @('Standard','CoopUS','CoopUSSR')){
        foreach($difficulty in @('Easy','Medium','Hard')){
            $preset=Resolve-AICFScenario -Catalog $catalog -Variant $entry.name -MatchMode $mode -Difficulty $difficulty
            $lines.Add("`t`tvariant.m_aPresets.Insert(`"$($preset.scenario)`");")
        }
    }
    $lines.Add("`t`tvariants.Insert(variant);")
}
if($pairs.Count -ne 9){throw 'Incomplete menu matrix'}
$lines.Add("`t}")
$lines.Add("`toverride string ResolveSourceProject(string path)")
$lines.Add("`t{")
foreach($project in $catalog.localProjects.PSObject.Properties){
    $suffix='/'+$project.Value.ToLowerInvariant()+'/addon.gproj'
    $lines.Add("`t`tif (path.EndsWith(`"$suffix`")) return `"$($project.Name)`";")
}
$lines.Add("`t`treturn super.ResolveSourceProject(path);")
$lines.Add("`t}")
$lines.Add('}')
$expected=($lines -join "`n")+"`n"
$path=Join-Path $RepositoryRoot 'AIConflictArland/Scripts/Game/AIConflictArland/Integration/AICF_ScenarioVariants.c'
if($Check){
    if(!(Test-Path -LiteralPath $path) -or [IO.File]::ReadAllText($path).Replace("`r`n","`n") -cne $expected){throw 'Scenario registry differs from catalog; run Update-AICFScenarioRegistry.ps1'}
}else{[IO.File]::WriteAllText($path,$expected,[Text.UTF8Encoding]::new($false))}
"Scenario registry: PASS; variants=9; presets=81; check=$Check"
